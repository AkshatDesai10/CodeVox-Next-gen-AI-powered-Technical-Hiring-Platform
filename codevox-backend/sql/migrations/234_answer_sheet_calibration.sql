CREATE TABLE IF NOT EXISTS ae_calibration_import_batches (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  assessment_id BIGINT UNSIGNED NULL,
  school_id BIGINT UNSIGNED NULL,
  program_id BIGINT UNSIGNED NULL,
  course_code VARCHAR(64) NULL,
  file_name VARCHAR(255) NOT NULL,
  file_hash VARCHAR(64) NULL,
  uploaded_by VARCHAR(64) NOT NULL,
  detected_layout VARCHAR(64) NULL,
  status ENUM('preview','imported','failed') NOT NULL DEFAULT 'preview',
  total_rows INT UNSIGNED NOT NULL DEFAULT 0,
  valid_rows INT UNSIGNED NOT NULL DEFAULT 0,
  invalid_rows INT UNSIGNED NOT NULL DEFAULT 0,
  preview_json JSON NULL,
  summary_json JSON NULL,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_ae_cal_import_assessment (assessment_id),
  KEY idx_ae_cal_import_program_course (program_id, course_code),
  KEY idx_ae_cal_import_created (created_at)
);

CREATE TABLE IF NOT EXISTS ae_calibration_benchmark_rows (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  import_batch_id BIGINT UNSIGNED NOT NULL,
  assessment_id BIGINT UNSIGNED NULL,
  submission_id BIGINT UNSIGNED NULL,
  viva_student_id BIGINT UNSIGNED NULL,
  enrollment_id VARCHAR(64) NULL,
  seat_number VARCHAR(64) NULL,
  question_number VARCHAR(32) NOT NULL,
  marks_max DECIMAL(8,2) NULL,
  human_marks DECIMAL(8,2) NULL,
  internal_marks DECIMAL(8,2) NULL,
  external_marks DECIMAL(8,2) NULL,
  final_marks DECIMAL(8,2) NULL,
  row_status ENUM('valid','invalid') NOT NULL DEFAULT 'valid',
  error_message VARCHAR(512) NULL,
  source_row_json JSON NULL,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_ae_cal_bench_batch (import_batch_id),
  KEY idx_ae_cal_bench_assessment_qn (assessment_id, question_number),
  KEY idx_ae_cal_bench_submission_qn (submission_id, question_number)
);

CREATE TABLE IF NOT EXISTS ae_calibration_runs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  assessment_id BIGINT UNSIGNED NOT NULL,
  school_id BIGINT UNSIGNED NULL,
  program_id BIGINT UNSIGNED NULL,
  course_code VARCHAR(64) NULL,
  source_import_batch_id BIGINT UNSIGNED NULL,
  status ENUM('queued','running','completed','failed') NOT NULL DEFAULT 'queued',
  assessment_type VARCHAR(64) NULL,
  triggered_by VARCHAR(64) NOT NULL,
  teacher_seed_json JSON NULL,
  sample_size INT UNSIGNED NOT NULL DEFAULT 0,
  compared_count INT UNSIGNED NOT NULL DEFAULT 0,
  agreement_pct DECIMAL(6,2) NULL,
  average_delta DECIMAL(8,2) NULL,
  average_abs_delta DECIMAL(8,2) NULL,
  confidence_pct DECIMAL(6,2) NULL,
  drift_direction VARCHAR(32) NULL,
  status_label ENUM('calibrated','drifting','off_key') NULL,
  recommendation_text TEXT NULL,
  config_json JSON NULL,
  summary_json JSON NULL,
  error_message VARCHAR(512) NULL,
  started_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_ae_cal_run_assessment (assessment_id),
  KEY idx_ae_cal_run_status (status),
  KEY idx_ae_cal_run_created (created_at)
);

CREATE TABLE IF NOT EXISTS ae_calibration_run_questions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  run_id BIGINT UNSIGNED NOT NULL,
  assessment_id BIGINT UNSIGNED NOT NULL,
  question_number VARCHAR(32) NOT NULL,
  ai_avg_marks DECIMAL(8,2) NULL,
  human_avg_marks DECIMAL(8,2) NULL,
  gap_marks DECIMAL(8,2) NULL,
  gap_pct DECIMAL(6,2) NULL,
  sample_size INT UNSIGNED NOT NULL DEFAULT 0,
  flag_label VARCHAR(64) NULL,
  detail_json JSON NULL,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_ae_cal_q_run (run_id),
  KEY idx_ae_cal_q_assessment_qn (assessment_id, question_number)
);

CREATE TABLE IF NOT EXISTS ae_calibration_actions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  assessment_id BIGINT UNSIGNED NULL,
  run_id BIGINT UNSIGNED NULL,
  import_batch_id BIGINT UNSIGNED NULL,
  action_type ENUM('preview_import','confirm_import','trigger_run','apply_to_rubric') NOT NULL,
  actor_user_id VARCHAR(64) NOT NULL,
  target_ref VARCHAR(128) NULL,
  notes TEXT NULL,
  payload_json JSON NULL,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_ae_cal_action_assessment (assessment_id),
  KEY idx_ae_cal_action_run (run_id),
  KEY idx_ae_cal_action_import (import_batch_id)
);
