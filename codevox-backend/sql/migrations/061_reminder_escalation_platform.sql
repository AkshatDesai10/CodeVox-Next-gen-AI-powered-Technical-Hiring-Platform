CREATE TABLE IF NOT EXISTS reminder_escalations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  instanceId BIGINT UNSIGNED NOT NULL,
  policyId BIGINT UNSIGNED NULL,
  level INT NOT NULL DEFAULT 1,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  targetUserId BIGINT UNSIGNED NULL,
  acknowledgedAt TIMESTAMP NULL,
  acknowledgedBy BIGINT UNSIGNED NULL,
  escalatedAt TIMESTAMP NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_res_instance (instanceId),
  CONSTRAINT fk_res_instance FOREIGN KEY (instanceId) REFERENCES reminder_instances (id) ON DELETE CASCADE,
  CONSTRAINT fk_res_policy FOREIGN KEY (policyId) REFERENCES reminder_escalation_policies (id) ON DELETE SET NULL,
  CONSTRAINT fk_res_target FOREIGN KEY (targetUserId) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_res_ack_by FOREIGN KEY (acknowledgedBy) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_digests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  userId BIGINT UNSIGNED NOT NULL,
  windowStart TIMESTAMP NOT NULL,
  windowEnd TIMESTAMP NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  instanceIds JSON NOT NULL,
  sentAt TIMESTAMP NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_rdig_user_status (userId, status),
  CONSTRAINT fk_rdig_user FOREIGN KEY (userId) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminder_suppressions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  dedupeKey VARCHAR(255) NOT NULL,
  suppressedUntil TIMESTAMP NOT NULL,
  reason VARCHAR(64) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_rsup_key_until (dedupeKey, suppressedUntil)
);

