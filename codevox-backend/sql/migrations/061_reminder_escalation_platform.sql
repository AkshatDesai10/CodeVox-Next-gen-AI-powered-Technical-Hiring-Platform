  UNIQUE KEY uq_rr_instance_user (instanceId, userId),
  CONSTRAINT fk_rr_instance FOREIGN KEY (instanceId) REFERENCES reminder_instances (id) ON DELETE CASCADE,
  CONSTRAINT fk_rr_user FOREIGN KEY (userId) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminder_channels (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  instanceId BIGINT UNSIGNED NOT NULL,
  channel VARCHAR(32) NOT NULL,
  config JSON NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rch_instance (instanceId),
  CONSTRAINT fk_rch_instance FOREIGN KEY (instanceId) REFERENCES reminder_instances (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminder_deliveries (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  instanceId BIGINT UNSIGNED NOT NULL,
  recipientUserId BIGINT UNSIGNED NOT NULL,
  channel VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  retryCount INT NOT NULL DEFAULT 0,
  lastError TEXT NULL,
  externalId VARCHAR(128) NULL,
  appNotificationId BIGINT UNSIGNED NULL,
  scheduledAt TIMESTAMP NULL,
  deliveredAt TIMESTAMP NULL,
  viewedAt TIMESTAMP NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rd_instance (instanceId),
  KEY idx_rd_recipient_status (recipientUserId, status),
  CONSTRAINT fk_rd_instance FOREIGN KEY (instanceId) REFERENCES reminder_instances (id) ON DELETE CASCADE,
  CONSTRAINT fk_rd_recipient FOREIGN KEY (recipientUserId) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminder_delivery_attempts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  deliveryId BIGINT UNSIGNED NOT NULL,
  attemptNumber INT NOT NULL,
