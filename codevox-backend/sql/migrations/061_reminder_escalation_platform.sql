-- Enterprise reminder & escalation platform

CREATE TABLE IF NOT EXISTS reminder_escalation_policies (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(128) NOT NULL,
  projectId BIGINT UNSIGNED NULL,
  steps JSON NOT NULL,
  createdBy BIGINT UNSIGNED NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rep_project (projectId),
  CONSTRAINT fk_rep_project FOREIGN KEY (projectId) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_rep_created_by FOREIGN KEY (createdBy) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_policies (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  scope VARCHAR(32) NOT NULL DEFAULT 'global',
  projectId BIGINT UNSIGNED NULL,
  quietHoursStart VARCHAR(8) NULL,
  quietHoursEnd VARCHAR(8) NULL,
  timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
  maxPerUserPerHour INT NOT NULL DEFAULT 20,
  dedupeWindowMinutes INT NOT NULL DEFAULT 120,
  criticalBypassQuietHours TINYINT(1) NOT NULL DEFAULT 1,
  config JSON NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rpol_scope (scope, projectId)
);

CREATE TABLE IF NOT EXISTS reminder_templates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(128) NOT NULL,
  scope VARCHAR(32) NOT NULL DEFAULT 'organization',
  projectId BIGINT UNSIGNED NULL,
  teamId BIGINT UNSIGNED NULL,
  ownerUserId BIGINT UNSIGNED NULL,
  subject VARCHAR(255) NOT NULL,
  bodyHtml TEXT NOT NULL,
  bodyText TEXT NULL,
  defaultChannels JSON NOT NULL,
  defaultPriority VARCHAR(16) NOT NULL DEFAULT 'medium',
  triggerHint VARCHAR(64) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rtpl_scope (scope, projectId),
  CONSTRAINT fk_rtpl_project FOREIGN KEY (projectId) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_rtpl_owner FOREIGN KEY (ownerUserId) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_rules (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(128) NOT NULL,
  projectId BIGINT UNSIGNED NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  triggerType VARCHAR(64) NOT NULL,
  triggerConfig JSON NOT NULL,
  conditions JSON NULL,
  delayMinutes INT NOT NULL DEFAULT 0,
  throttleMinutes INT NOT NULL DEFAULT 0,
  templateId BIGINT UNSIGNED NULL,
  escalationPolicyId BIGINT UNSIGNED NULL,
  priority VARCHAR(16) NOT NULL DEFAULT 'medium',
  channels JSON NOT NULL,
  createdBy BIGINT UNSIGNED NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rr_project (projectId),
  KEY idx_rr_trigger (triggerType, enabled),
  CONSTRAINT fk_rr_project FOREIGN KEY (projectId) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_rr_template FOREIGN KEY (templateId) REFERENCES reminder_templates (id) ON DELETE SET NULL,
  CONSTRAINT fk_rr_escalation FOREIGN KEY (escalationPolicyId) REFERENCES reminder_escalation_policies (id) ON DELETE SET NULL,
  CONSTRAINT fk_rr_created_by FOREIGN KEY (createdBy) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_batches (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  mode VARCHAR(32) NOT NULL,
  querySpec JSON NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  totalCount INT NOT NULL DEFAULT 0,
  processedCount INT NOT NULL DEFAULT 0,
  createdBy BIGINT UNSIGNED NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_rb_status (status),
  CONSTRAINT fk_rb_created_by FOREIGN KEY (createdBy) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_instances (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ruleId BIGINT UNSIGNED NULL,
  batchId BIGINT UNSIGNED NULL,
  templateId BIGINT UNSIGNED NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  priority VARCHAR(16) NOT NULL DEFAULT 'medium',
  subject VARCHAR(255) NOT NULL,
  bodyHtml TEXT NULL,
  bodyText TEXT NULL,
  entityType VARCHAR(32) NULL,
  entityId VARCHAR(64) NULL,
  projectId BIGINT UNSIGNED NULL,
  scheduledAt TIMESTAMP NULL,
  firedAt TIMESTAMP NULL,
  expiresAt TIMESTAMP NULL,
  dedupeKey VARCHAR(255) NULL,
  metadata JSON NULL,
  createdBy BIGINT UNSIGNED NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  inactive TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY uq_ri_dedupe (dedupeKey),
  KEY idx_ri_status_scheduled (status, scheduledAt),
  KEY idx_ri_project (projectId),
  KEY idx_ri_entity (entityType, entityId),
  CONSTRAINT fk_ri_rule FOREIGN KEY (ruleId) REFERENCES reminder_rules (id) ON DELETE SET NULL,
  CONSTRAINT fk_ri_batch FOREIGN KEY (batchId) REFERENCES reminder_batches (id) ON DELETE SET NULL,
  CONSTRAINT fk_ri_template FOREIGN KEY (templateId) REFERENCES reminder_templates (id) ON DELETE SET NULL,
  CONSTRAINT fk_ri_project FOREIGN KEY (projectId) REFERENCES projects (id) ON DELETE SET NULL,
  CONSTRAINT fk_ri_created_by FOREIGN KEY (createdBy) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS reminder_recipients (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  instanceId BIGINT UNSIGNED NOT NULL,
  userId BIGINT UNSIGNED NOT NULL,
  roleHint VARCHAR(32) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
